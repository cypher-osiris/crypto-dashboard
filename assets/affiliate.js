/* Affiliate links — driven by data/config.json, geo-gated client-side.
 *   Bitunix (affiliate.bitunix_url)   NON-US visitors only (Bitunix bans US users).
 *   Coinbase (US visitors only): affiliate.coinbase_advanced_url = main "Trade on Coinbase Advanced" buttons,
 *     affiliate.coinbase_url = small "New to crypto? Get started on Coinbase" link. Both empty => nothing is shown.
 * Fail closed: all affiliate UI stays hidden until the country is known. Lookup order:
 *   ?geo=XX debug override -> sessionStorage cache -> api.country.is -> ipapi.co/country -> Intl timeZone (US zones => US).
 * If everything fails (no country, no time zone) nothing is shown.
 * Coinbase links are referral JOIN links used exactly as configured (no per-coin path/query is ever appended, so the
 *   referral code is never dropped). They open Coinbase's "Sign up to activate your referral" page; an existing member
 *   (e.g. the referrer himself) only sees that page plus "Already have an account?". So every Coinbase per-trade button
 *   carries a one-line note saying so and naming the pair to open after signing in. Coins with no Coinbase product in
 *   data/coins.json (ZBCN, XDC: card data-cb="") get NO Coinbase trade button, only a short "not listed on Coinbase" note.
 * Bitunix: always the general referral link (no per-pair URL). Spot ideas (leverage 1, card data-lev="1") are labelled
 *   "Buy <SYM> spot on Bitunix" (XDC has no Bitunix perpetual; XDC/USDT spot is listed).
 * Kraken (affiliate.kraken_url = sign-up link with ?inviteCode=, affiliate.kraken_code shown in the note): a SECONDARY
 *   "Buy <SYM> spot on Kraken" button on LONG slate cards whose coin has a pair in affiliate.kraken_pairs
 *   (coin id -> Kraken spot pair, checked against Kraken's public AssetPairs), plus one in the calculator.
 *   US visitors: always (it's the only US option for XDC/ZBCN, which Coinbase doesn't list). Non-US visitors: only when
 *   affiliate.kraken_non_us is true (off by default: Kraken credits referrals only within the referrer's country/EEA).
 *   Spot only: no leverage/"setup" wording, never on short ideas (spot can't short). Empty kraken_url => nothing shown.
 * Uphold (affiliate.uphold_url, used exactly as given): "Buy <SYM> on Uphold" on LONG slate cards whose coin is in
 *   affiliate.uphold_assets (coin id -> Uphold code, from api.uphold.com/v0/assets) AND has no Coinbase product
 *   (data-cb="": XDC, ZBCN), so cards stay at <= 2-3 links. Coins in affiliate.uphold_first (XDC: Bobby's own venue) get
 *   Uphold first, then Kraken; otherwise Kraken first. US only: country "US" (not territories: Uphold doesn't serve
 *   USVI/UM and opens no new accounts in PR/GU/AS/MP); non-US only if affiliate.uphold_non_us is true (default false).
 * Coin pages (/xdc/ etc., generated by scripts/build_pages.py): #aff-coin (data-coin, data-sym, data-cb) gets the
 *   "Buy <SYM>" buttons for the visitor's region: US = Coinbase (coinbase_url join link, else Advanced; only if data-cb),
 *   Kraken (kraken_pairs), Uphold (uphold_assets; first for uphold_first coins), max 3; non-US = Bitunix (spot), plus
 *   Kraken/Uphold only when their *_non_us flags are true. #aff-ledger shows a Ledger button to everyone only when
 *   affiliate.ledger_url is set (empty = nothing); the dashboard footer line #aff-ledger-foot likewise. Note text =
 *   affiliate.ledger_note (quotes Ledger's own referral page), button label = affiliate.ledger_page_label. config.json is resolved relative to this script, so it works from any page.
 * Hardware-wallet pick (#wallet-pick, under the calculator): shown to ALL visitors, no geo gate.
 *   affiliate.dcent_url (+ dcent_label) = main button; affiliate.ledger_url (+ ledger_label) = second option, hidden while empty. */
(() => {
  "use strict";
  const DISCLOSURE = "Some links are affiliate links; we may earn a commission at no cost to you. Paper trades, not financial advice.";
  const CACHE_KEY = "lumi_geo_v1";
  const US_CODES = new Set(["US", "PR", "GU", "VI", "AS", "MP", "UM"]); // US + territories
  const US_ZONES = new Set(["America/New_York", "America/Chicago", "America/Denver", "America/Los_Angeles", "America/Phoenix",
    "America/Anchorage", "America/Detroit", "America/Boise", "Pacific/Honolulu", "America/Juneau", "America/Sitka",
    "America/Nome", "America/Yakutat", "America/Metlakatla", "America/Adak", "America/Menominee", "America/Puerto_Rico",
    "US/Eastern", "US/Central", "US/Mountain", "US/Pacific", "US/Arizona", "US/Alaska", "US/Hawaii", "US/Michigan",
    // legacy/canonical aliases browsers may report (e.g. Chrome turns America/Indiana/Indianapolis into America/Indianapolis)
    "America/Indianapolis", "America/Fort_Wayne", "America/Knox_IN", "America/Louisville", "America/Shiprock", "America/Atka",
    "Navajo", "US/East-Indiana", "US/Indiana-Starke", "US/Aleutian", "EST5EDT", "CST6CDT", "MST7MDT", "PST8PDT",
    // territories
    "America/St_Thomas", "America/Virgin", "Pacific/Guam", "Pacific/Saipan", "Pacific/Pago_Pago", "Pacific/Samoa", "US/Samoa", "Pacific/Johnston"]);
  const US_ZONE_PREFIXES = ["America/Indiana/", "America/Kentucky/", "America/North_Dakota/"];
  const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const okUrl = (u) => /^https:\/\/[^\s"'<>]+$/i.test(u);
  const cc = (s) => { const c = String(s || "").trim().toUpperCase(); return /^[A-Z]{2}$/.test(c) ? c : ""; };
  const CONFIG_URL = (() => { try { return new URL("../data/config.json", document.currentScript.src).href; } catch (e) { return "data/config.json"; } })();
  let P = null; // active program: { name, url, label, slate, aria, extra: {url, text} | null }
  let U = null; // Uphold: { url, label, assets: {coinId: code}, first: Set(coinId) } | null
  let K = null; // Kraken secondary: { url, code, label, pairs: {coinId: "XDC/USD"} } | null

  // ---- geo ---------------------------------------------------------------------------------------
  async function fetchCountry(url, pick, ms) {
    const ctl = new AbortController(); const t = setTimeout(() => ctl.abort(), ms);
    try {
      const r = await fetch(url, { signal: ctl.signal, cache: "no-store" });
      if (!r.ok) return "";
      return cc(pick(await r.text()));
    } catch (e) { return ""; } finally { clearTimeout(t); }
  }
  function zoneIsUS() {
    let z = ""; try { z = Intl.DateTimeFormat().resolvedOptions().timeZone || ""; } catch (e) { /* none */ }
    if (!z) return null; // unknown
    return US_ZONES.has(z) || US_ZONE_PREFIXES.some((p) => z.startsWith(p));
  }
  /* -> { us: true|false|null, country, src }  (us === null => unknown => show nothing) */
  async function geo() {
    const q = cc(new URLSearchParams(location.search).get("geo"));
    if (q) return { us: US_CODES.has(q), country: q, src: "override" }; // debug, never cached
    try { const c = JSON.parse(sessionStorage.getItem(CACHE_KEY) || "null"); if (c && typeof c.us === "boolean") return c; } catch (e) { /* ignore */ }
    let country = await fetchCountry("https://api.country.is/", (t) => { try { return JSON.parse(t).country; } catch (e) { return ""; } }, 2500);
    let src = "country.is";
    if (!country) { country = await fetchCountry("https://ipapi.co/country/", (t) => t, 2500); src = "ipapi.co"; }
    let res;
    if (country) res = { us: US_CODES.has(country), country, src };
    else { const z = zoneIsUS(); res = { us: z, country: z === null ? "" : (z ? "US?" : "non-US?"), src: "timezone" }; }
    if (typeof res.us === "boolean") { try { sessionStorage.setItem(CACHE_KEY, JSON.stringify(res)); } catch (e) { /* private mode */ } }
    return res;
  }

  // ---- render ------------------------------------------------------------------------------------
  const link = (text, cls) => `<a class="aff-btn ${cls || ""}" href="${esc(P.url)}" rel="sponsored noopener" target="_blank">${esc(text)}<span aria-hidden="true"> ↗</span></a>`;
  const extra = () => P.extra ? `<a class="aff-extra" href="${esc(P.extra.url)}" rel="sponsored noopener" target="_blank">${esc(P.extra.text)}<span aria-hidden="true"> ↗</span></a>` : "";
  const note = () => `<p class="aff-note">${esc(DISCLOSURE)}</p>`;
  const kbtn = (text, aria) => `<a class="aff-btn aff-kraken" href="${esc(K.url)}" rel="sponsored noopener" target="_blank" aria-label="${esc(aria)} (referral link, opens in a new tab)">${esc(text)}<span aria-hidden="true"> ↗</span></a>`;
  const kcode = () => K.code ? ` Referral code: ${K.code}.` : "";
  /* Kraken block for one slate card ("" when the coin has no Kraken pair or the idea isn't a long) */
  function upholdFor(card, sym) {
    if (!U || card.dataset.dir === "short" || card.dataset.cb !== "") return "";
    if (!U.assets[card.dataset.coin || ""]) return "";
    const t = U.label.replace("{SYM}", sym);
    return `<a class="aff-btn aff-uphold" href="${esc(U.url)}" rel="sponsored noopener" target="_blank" aria-label="${esc(t)} (referral link, opens in a new tab)">${esc(t)}<span aria-hidden="true"> ↗</span></a>` +
      `<p class="aff-note">Referral link; new Uphold accounts. Spot only. Availability varies by state/country (not available in New York).</p>`;
  }
  function krakenFor(card, sym) {
    if (!K || card.dataset.dir === "short") return "";
    const pair = K.pairs[card.dataset.coin || ""];
    if (!pair) return "";
    const base = pair.split("/")[0];
    const listed = base !== sym ? ` (Kraken's ticker for ${sym})` : "";
    return kbtn(`Buy ${sym} spot on Kraken`, `Buy ${sym} spot on Kraken`) +
      `<p class="aff-note">Referral link; new Kraken accounts.${esc(kcode())} Spot only, no leverage: ${esc(pair)}${esc(listed)}. ` +
      `Already have an account? Sign in and open ${esc(pair)}. Availability varies by state/country.</p>`;
  }

  function decorateSlate() {
    document.querySelectorAll(".slate-card[data-slate]").forEach((card) => {
      if (card.querySelector(".aff-wrap")) return;
      if (!(card.classList.contains("pending") || card.classList.contains("open"))) return; // active ideas only
      const sym = card.dataset.sym || (card.querySelector(".coin-mark") || {}).textContent || "";
      const spot = card.dataset.lev === "1";
      const w = document.createElement("div");
      w.className = "aff-wrap";
      const kr = krakenFor(card, sym), up = upholdFor(card, sym);
      if (P.key === "coinbase" && card.dataset.cb === "") {
        // not listed on Coinbase => a Coinbase "trade" button would lead nowhere useful; Uphold/Kraken (if listed) take its place
        const venues = [up && "Uphold", kr && "Kraken"].filter(Boolean);
        const spot = U && U.first.has(card.dataset.coin) ? up + kr : kr + up;
        if (venues.length && !(U && U.first.has(card.dataset.coin))) venues.reverse();
        w.innerHTML = spot
          ? `<p class="aff-note">${esc(sym)} isn't listed on Coinbase; ${venues.join(" and ")} ${venues.length > 1 ? "list" : "lists"} it for spot.</p>` + spot + note()
          : `<p class="aff-note">${esc(sym)} isn't listed on Coinbase, so there's no Coinbase button for this idea.</p>`;
      } else {
        const lbl = P.key === "bitunix" && spot ? `Buy ${sym} spot on Bitunix` : P.slate;
        const hint = P.key === "coinbase" ? `<p class="aff-note">Referral sign-up link (new Coinbase accounts). Already have one? Sign in at Coinbase Advanced and open ${esc(card.dataset.cb || sym)}.</p>` : "";
        w.innerHTML = link(lbl, "") + hint + kr + note();
        const a = w.querySelector("a");
        if (sym) a.setAttribute("aria-label", `${P.key === "bitunix" && spot ? lbl : P.aria(sym)} (affiliate link, opens in a new tab)`);
      }
      const why = card.querySelector(":scope > details.why");
      why ? card.insertBefore(w, why) : card.appendChild(w);
    });
  }

  function apply() {
    const cta = document.getElementById("aff-cta");
    if (cta) { cta.innerHTML = link(P.label, "sm") + extra() + `<a class="aff-tag" href="#aff-foot">Affiliate link · disclosure</a>`; cta.hidden = false; }
    const calc = document.getElementById("aff-calc");
    const cbHint = P.key === "coinbase" ? `<p class="aff-note">Coinbase referral sign-up page. Existing members: sign in on Coinbase as usual.</p>` : "";
    const kCalc = K ? kbtn(K.label, K.label) + `<p class="aff-note">Kraken referral link; new Kraken accounts.${esc(kcode())} Spot only, no leverage.</p>` : "";
    if (calc) { calc.innerHTML = link(P.label, "") + extra() + cbHint + kCalc + note(); calc.hidden = false; }
    const foot = document.getElementById("aff-foot");
    if (foot) { foot.textContent = DISCLOSURE; foot.hidden = false; }
    decorateSlate();
    const grid = document.getElementById("slate-grid");
    if (grid) new MutationObserver(decorateSlate).observe(grid, { childList: true, subtree: true });
  }

  function renderWallet(a, s) {
    const box = document.getElementById("wallet-pick");
    const dcent = s("dcent_url"), ledger = s("ledger_url");
    if (!box || !dcent) return;
    const btn = (u, t, cls) => `<a class="aff-btn ${cls}" href="${esc(u)}" rel="sponsored noopener" target="_blank">${esc(t)}<span aria-hidden="true"> ↗</span></a>`;
    box.innerHTML = `<div class="w-ico" aria-hidden="true">🔐</div><div><h3>Keep your crypto safe</h3>` +
      `<p class="w-copy">Don't leave long-term holdings on an exchange. A hardware wallet keeps your keys offline. Lumi's pick: <b>D'CENT Biometric Wallet</b>.</p>` +
      `<div class="w-btns">${btn(dcent, String(a.dcent_label || "Get the D'CENT Biometric Wallet"), "sm")}` +
      (ledger ? btn(ledger, String(a.ledger_label || "Or choose Ledger"), "sm") : "") +
      `<a class="aff-tag" href="#aff-foot">Affiliate link · disclosure</a></div></div>`;
    box.hidden = false;
    const foot = document.getElementById("aff-foot");
    if (foot) { foot.textContent = DISCLOSURE; foot.hidden = false; }
    document.documentElement.classList.add("has-wallet-aff");
  }

  function renderLedgerHook(a, s) {
    const u = s("ledger_url");
    if (!u) return; // unset => show nothing
    const n = String(a.ledger_note || "Referral link: Ledger's referral program, which may give you a reward on your first order.");
    const box = document.getElementById("aff-ledger"); // coin pages: self-custody section
    if (box) {
      box.innerHTML = `<a class="aff-btn sm aff-ledger" href="${esc(u)}" rel="sponsored noopener" target="_blank" aria-label="Get a Ledger hardware wallet (referral link, opens in a new tab)">${esc(String(a.ledger_page_label || "Get a Ledger"))}<span aria-hidden="true"> ↗</span></a>` +
        `<p class="aff-note">${esc(n)}</p>`;
      box.hidden = false;
    }
    const lf = document.getElementById("aff-ledger-foot"); // dashboard footer: one quiet line
    if (lf) {
      lf.innerHTML = `Holding long term? Self-custody with <a href="${esc(u)}" rel="sponsored noopener" target="_blank">Ledger</a><span aria-hidden="true"> ↗</span> <span class="aff-note-inline">(${esc(n)})</span>`;
      lf.hidden = false;
    }
    if (!box && !lf) return;
    const foot = document.getElementById("aff-foot");
    if (foot) { foot.textContent = DISCLOSURE; foot.hidden = false; }
  }

  /* coin page "how to buy" buttons for the visitor's region */
  function renderCoinPage(a, s) {
    const box = document.getElementById("aff-coin");
    if (!box || !P) return;
    const id = box.dataset.coin || "", sym = box.dataset.sym || "", cb = box.dataset.cb || "";
    const btn = (u, t, cls, n) => `<a class="aff-btn ${cls}" href="${esc(u)}" rel="sponsored noopener" target="_blank" aria-label="${esc(t)} (referral link, opens in a new tab)">${esc(t)}<span aria-hidden="true"> ↗</span></a>` + (n ? `<p class="aff-note">${esc(n)}</p>` : "");
    const out = [];
    if (P.key === "coinbase" && cb) {
      const u = s("coinbase_url") || s("coinbase_advanced_url");
      if (u) out.push(btn(u, `Buy ${sym} on Coinbase`, "", `Referral sign-up link (new Coinbase accounts). Already have one? Sign in and search ${cb}.`));
    }
    if (P.key === "bitunix") out.push(btn(P.url, `Buy ${sym} on Bitunix`, "", `Referral link; new Bitunix accounts. ${sym}/USDT spot.`));
    const kp = K && K.pairs[id];
    const kr = kp ? btn(K.url, `Buy ${sym} on Kraken`, "aff-kraken", `Referral link; new Kraken accounts.${kcode()} Spot only: ${kp}. Availability varies by state/country.`) : "";
    const up = U && U.assets[id] ? btn(U.url, `Buy ${sym} on Uphold`, "aff-uphold", "Referral link; new Uphold accounts. Spot only. Availability varies by state/country (not available in New York).") : "";
    if (U && U.first.has(id)) out.unshift(...[up, kr].filter(Boolean)); else out.push(...[kr, up].filter(Boolean));
    if (!out.length) return;
    box.innerHTML = `<p class="aff-note"><b>${P.key === "coinbase" ? "Exchanges for US visitors" : "Exchange for your region"}</b></p>` + out.slice(0, 3).join("") + note();
    box.hidden = false;
  }

  async function start() {
    try {
      const r = await fetch(`${CONFIG_URL}?v=${Date.now()}`, { cache: "no-store" });
      if (!r.ok) return;
      const a = ((await r.json()) || {}).affiliate || {};
      const s = (k) => { const u = String(a[k] || "").trim(); return okUrl(u) ? u : ""; };
      renderWallet(a, s); // all visitors, before any geo lookup
      renderLedgerHook(a, s);
      const bitunix = s("bitunix_url"), cbAdv = s("coinbase_advanced_url"), cbJoin = s("coinbase_url");
      if (!bitunix && !cbAdv && !cbJoin) return; // nothing configured => no lookup, no UI
      const g = await geo();
      document.documentElement.dataset.geo = g.us === null ? "unknown" : (g.us ? "us" : "non-us");
      if (g.us === false && bitunix) {
        P = { key: "bitunix", url: bitunix, label: String(a.label || "Trade on Bitunix"), slate: "Copy this paper trade on Bitunix",
              aria: (sym) => `Copy this ${sym} paper trade on Bitunix`, extra: null };
      } else if (g.us === true && (cbAdv || cbJoin)) {
        // US: no leveraged perps on Coinbase for most users => neutral wording, no "setup" language
        const lbl = cbAdv ? String(a.coinbase_label || "Trade on Coinbase Advanced") : "Get started on Coinbase";
        P = { key: "coinbase", url: cbAdv || cbJoin, label: lbl, slate: lbl, aria: (sym) => `${lbl} (${sym})`,
              extra: cbAdv && cbJoin ? { url: cbJoin, text: "New to crypto? Get started on Coinbase" } : null };
      }
      const kUrl = s("kraken_url");
      const kPairs = (a.kraken_pairs && typeof a.kraken_pairs === "object") ? a.kraken_pairs : {};
      if (P && kUrl && (g.us === true || (g.us === false && a.kraken_non_us === true))) {
        const code = String(a.kraken_code || "").trim();
        K = { url: kUrl, code: /^[A-Za-z0-9]{4,32}$/.test(code) ? code : "", label: String(a.kraken_label || "Buy spot on Kraken"),
              pairs: Object.fromEntries(Object.entries(kPairs).filter(([, v]) => /^[A-Z0-9]{2,12}\/USD[A-Z]?$/.test(String(v)))) };
      }
      const uUrl = s("uphold_url");
      const uAssets = (a.uphold_assets && typeof a.uphold_assets === "object") ? a.uphold_assets : {};
      if (P && uUrl && (g.country === "US" || g.country === "US?" || (g.us === false && a.uphold_non_us === true))) {
        U = { url: uUrl, label: String(a.uphold_label || "Buy {SYM} on Uphold"),
              assets: Object.fromEntries(Object.entries(uAssets).filter(([, v]) => /^[A-Z0-9]{2,12}$/.test(String(v)))),
              first: new Set(Array.isArray(a.uphold_first) ? a.uphold_first.map(String) : []) };
      }
      if (!P) return; // unknown country, or no link for this region => keep everything hidden
      document.documentElement.classList.add("has-aff", "aff-" + P.key);
      apply();
      renderCoinPage(a, s);
    } catch (e) { /* config missing/invalid => no affiliate UI */ }
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start); else start();
})();
