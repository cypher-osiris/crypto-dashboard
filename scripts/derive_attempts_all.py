#!/usr/bin/env python3
"""Derive the grey 'Test payment not accepted yet on XRPL' label for EVERY seller on the curated trust list
(scripts/trust_attempts.json, read by scripts/site_pages.py and, via #tr-att, assets/trust.js).

A seller gets the label when it has zero completed paid test-buys and at least one signed XRPL test payment it
rejected (a buy_not_validated line in the test-buy log, or a tx already recorded in trust_attempts.json). The label
shows the real attempt count and first-attempt date and links to the seller's right to reply. It is informational
only and never part of the score; it disappears on its own once a paid test-buy completes.

publish.sh runs this on every publish (before build_pages.py) and stages scripts/trust_attempts.json.
  python3 scripts/derive_attempts_all.py           # rewrite scripts/trust_attempts.json if it changed, print it if so
  python3 scripts/derive_attempts_all.py --dry-run # print the result, write nothing
Inputs: TRUST_TESTBUYS_LOG (path to the private test-buy log; required, no default); vendors from
https://api.lumitrades.io/v1/trust/vendors, falling back to the build cache state/trust_vendors.json.
If neither the log nor the vendor list can be read, the existing file is left untouched (exit 0)."""
import datetime as dt, json, os, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "scripts", "trust_attempts.json")
LOG = os.environ.get("TRUST_TESTBUYS_LOG", "")
CACHE = os.path.join(ROOT, "state", "trust_vendors.json")
API = "https://api.lumitrades.io/v1/trust/vendors"
NOTE = ("Generated by scripts/derive_attempts_all.py on every publish (do not hand-edit). Every seller on the curated list "
        "with zero completed paid test-buys and at least one signed XRPL test payment it did not accept gets the grey, "
        "unscored 'Test payment not accepted yet' label. count = distinct signed XRPL test payments to the seller's pay-to "
        "that it answered with a rejection and that never reached the ledger (buy_not_validated in the test-buy log, plus "
        "hashes already recorded here); plan/skip/dry-run lines are not attempts.")


def vendors():
    try:
        req = urllib.request.Request(API, headers={"User-Agent": "lumitrades-build/1"})
        d = json.load(urllib.request.urlopen(req, timeout=20))
    except Exception:
        try:
            with open(CACHE, encoding="utf-8") as f:
                d = json.load(f)
        except Exception:
            return None
    d = d.get("vendors", d) if isinstance(d, dict) else d
    return d if isinstance(d, list) and d else None


def main():
    dry = "--dry-run" in sys.argv
    try:
        with open(OUT, encoding="utf-8") as f:
            snap = json.load(f)
    except Exception:
        snap = {}
    old_v = snap.get("vendors") or {}
    vs = vendors()
    if vs is None or not os.path.exists(LOG):
        print("derive_attempts_all: vendor list or test-buy log unavailable; keeping trust_attempts.json", file=sys.stderr)
        return 0
    rej = {}
    with open(LOG, encoding="utf-8") as f:
        for line in f:
            try:
                e = json.loads(line)
            except ValueError:
                continue
            if isinstance(e, dict) and e.get("event") == "buy_not_validated" and e.get("vendor") and e.get("tx"):
                rej.setdefault(e["vendor"], {})[e["tx"]] = e.get("ts")
    out = {}
    for v in vs:
        vid = str(v.get("id") or "")
        if not vid:
            continue
        s = v.get("samples") or {}
        if s.get("paid_test_buys") or v.get("last_paid_observation"):
            continue  # a completed test-buy: no label
        txs = dict(rej.get(vid, {}))
        old = old_v.get(vid) or {}
        for h in old.get("tx_hashes") or []:
            txs.setdefault(h, None)
        if not txs:
            continue
        ts = sorted(t for t in list(txs.values()) + [old.get("first_attempt"), old.get("last_attempt")] if t)
        if not ts:
            continue
        out[vid] = {"network": "xrpl:0", "count": len(txs), "first_attempt": ts[0], "last_attempt": ts[-1],
                    "tx_hashes": sorted(txs)}
    if {k: {kk: vv for kk, vv in x.items()} for k, x in old_v.items()} == out and snap.get("_note") == NOTE:
        return 0  # unchanged: keep as_of so the file (and the commit) don't churn
    doc = {"_note": NOTE, "as_of": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "vendors": out}
    txt = json.dumps(doc, indent=1) + "\n"
    if dry:
        sys.stdout.write(txt)
        return 0
    with open(OUT + ".tmp", "w", encoding="utf-8") as f:
        f.write(txt)
    os.replace(OUT + ".tmp", OUT)
    print(os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
