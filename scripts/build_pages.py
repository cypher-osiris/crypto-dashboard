def fp(p):
    """Price like the site's fmtPrice."""
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "—"
    a = abs(p)
    d = 0 if a >= 1000 else 3 if a >= 1 else 4 if a >= 0.1 else 5 if a >= 0.01 else 6
    s = f"{p:,.{d}f}"
    if "." in s:
        s = s.rstrip("0")
        if s.endswith("."):
            s = s[:-1]
        if "." in s and len(s.split(".")[1]) < min(d, 2):
            s += "0" * (min(d, 2) - len(s.split(".")[1]))
    return "$" + s


def lvl(p):
    return fp(p)[1:]


def pc(v, digits=2):
    if v is None:
        return f'<span class="muted">{_("n/a")}</span>'
    cls = "up" if v > 0 else "down" if v < 0 else "flat"
    return f'<span class="{cls}">{"+" if v > 0 else ""}{v:.{digits}f}%</span>'


def pct_txt(v, digits=1):
    return _("n/a") if v is None else f'{"+" if v > 0 else ""}{v:.{digits}f}%'


def ctime(iso, with_time=True):
    if not iso:
        return "—"
    t = dt.datetime.fromisoformat(str(iso).replace("Z", "+00:00"))
    if t.tzinfo is None:
        t = t.replace(tzinfo=CT)
    return L.date(t.astimezone(CT), with_time)


def paragraphs(text, per=4):
    sents = re.split(r"(?<=[.!?])\s+(?=[A-Z(\"'])", (text or "").strip())
    out = [" ".join(sents[i:i + per]) for i in range(0, len(sents), per)]
    return "".join(f"<p>{E(p)}</p>" for p in out if p)


