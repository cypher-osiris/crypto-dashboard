#!/usr/bin/env python3
"""Static site build (stdlib only): the trust-only pages in every language, sitemap.xml and feed.xml.

  python3 scripts/build_pages.py            # writes every generated page, sitemap.xml and feed.xml
  python3 scripts/build_pages.py --quiet    # prints only the changed paths (one per line)
  python3 scripts/build_pages.py --paths    # all generated paths + index.html if changed (used by publish.sh)

Pages: /agents/, /trust/, /how-it-works/, /privacy/, /trust-policy/, /contact/, /top-sellers/ (scripts/site_pages.py and the
page modules it calls), /sellers/<slug>/ (scripts/seller_pages.py), /blog/ (scripts/blog_index.py) and the language homepages
(/<lang>/index.html from the English index.html).

The site is trust-only: it checks x402 sellers and publishes the evidence. Old URLs from before Oct 25, 2026 are not
generated any more and answer 404 (the published site is assembled by scripts/build_site.py from an allowlist).
Only files whose content changed are rewritten. publish.sh runs this automatically when publishing.
"""
import datetime as dt, html, json, math, os, re, sys, types
from zoneinfo import ZoneInfo

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import policy_page  # /trust-policy/ (conflicts policy; footer link in every language in policy_page.LIVE_LANGS)
import site_chrome  # shared head, nav + footer (site_nav, foot_brand) for every generated page
import i18n  # assets/i18n/<lang>.json; every page is rendered once per language (English at /, others under /<lang>/)

L = i18n.Lang("en")  # current language while building (set per pass in build())


def _(_key, **kw):
    return L.t(_key, **kw)


def T(_key, **kw):
    """Translated HTML: the string itself is trusted markup, the values are escaped."""
    return L.t(_key, **{k: E(v) for k, v in kw.items()})

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://lumitrades.io/"
CT = ZoneInfo("America/Chicago")

E = lambda s: html.escape(str(s if s is not None else ""), quote=True)


def load(name):
    with open(os.path.join(ROOT, "data", name), encoding="utf-8") as f:
        return json.load(f)


def fp(p):
    """Price like the site's fmtPrice."""
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "—"
    a = abs(p)
    d = 0 if a >= 1000 else 3 if a >= 1 else 4 if a >= 0.1 else 5 if a >= 0.01 else 6
    s = f"{p:,.{d}f}"
    if "." in s:
        s = s.rstrip("0")
        if s.endswith("."):
            s = s[:-1]
        if "." in s and len(s.split(".")[1]) < min(d, 2):
            s += "0" * (min(d, 2) - len(s.split(".")[1]))
    return "$" + s


def lvl(p):
    return fp(p)[1:]


def pc(v, digits=2):
    if v is None:
        return f'<span class="muted">{_("n/a")}</span>'
    cls = "up" if v > 0 else "down" if v < 0 else "flat"
    return f'<span class="{cls}">{"+" if v > 0 else ""}{v:.{digits}f}%</span>'


def pct_txt(v, digits=1):
    return _("n/a") if v is None else f'{"+" if v > 0 else ""}{v:.{digits}f}%'


def ctime(iso, with_time=True):
    if not iso:
        return "—"
    t = dt.datetime.fromisoformat(str(iso).replace("Z", "+00:00"))
    if t.tzinfo is None:
        t = t.replace(tzinfo=CT)
    return L.date(t.astimezone(CT), with_time)


def paragraphs(text, per=4):
    sents = re.split(r"(?<=[.!?])\s+(?=[A-Z(\"'])", (text or "").strip())
    out = [" ".join(sents[i:i + per]) for i in range(0, len(sents), per)]
    return "".join(f"<p>{E(p)}</p>" for p in out if p)


def free(obj, field, default=""):
    return L.free(obj, field, E, default)



FEED_LINK = '<link rel="alternate" type="application/atom+xml" title="Lumi Trades" href="https://lumitrades.io/feed.xml">'  # /feed.xml (scripts/feed.py)


def head_i18n(path, langs):
    """hreflang alternates + og:locale for a page at `path` (relative to a language root)."""
    alt = i18n.alternates(path, langs)
    loc = f'<meta property="og:locale" content="{L.meta.get("og_locale", "en_US")}">'
    loc += "".join(f'\n<meta property="og:locale:alternate" content="{x.meta.get("og_locale")}">' for x in langs if x.code != L.code)
    return alt + "\n" + loc + "\n" + FEED_LINK


def i18n_scripts(R):
    """assets/i18n.js (switcher memory + language suggestion) and, on translated pages, the string bundle."""
    V = VERSION
    return (("" if L.en else f'<script src="{R}assets/i18n/{L.code}.js?v={V}" defer></script>\n')  # strings first
            + f'<script src="{R}assets/i18n.js?v={V}" defer></script>\n')


VERSION = "1"


IHEAD = ("<!-- i18n-head:start (generated by scripts/build_pages.py) -->", "<!-- i18n-head:end -->")
SEOHEAD = ("<!-- seo-head:start (generated by scripts/build_pages.py) -->", "<!-- seo-head:end -->")


def seo_head(url, prices_tbl):
    """Homepage keywords meta + JSON-LD (WebSite, Organization, WebAPI with an AggregateOffer), in language L."""
    import seo
    # trust-only home page: the trust list's Dataset lives on /trust/
    ld = [seo.website(_, url, L.code, _(INDEX_DESC)), seo.organization(_, "home"), seo.web_api(_, L.code, prices_tbl, full=False)]
    return (f'<meta name="keywords" content="{E(seo.keywords(_, "home", L.en))}">\n'
            '<script type="application/ld+json">' + json.dumps(ld, ensure_ascii=False).replace("</", "<\\/") + "</script>")
ISW = ("<!-- lang-switch:start (generated by scripts/build_pages.py) -->", "<!-- lang-switch:end -->")
HSTATS = ("<!-- hero-stats:start (generated by scripts/build_pages.py) -->", "<!-- hero-stats:end -->")  # homepage stat chips, from the live API
SWEEP = ("<!-- sweep:start (generated by scripts/build_pages.py) -->", "<!-- sweep:end -->")  # dated XRPL Bazaar sweep, from the live API
TSTEPS = ("<!-- trust-steps:start (generated by scripts/build_pages.py) -->", "<!-- trust-steps:end -->")  # homepage "how the checks work" steps + chain badges (static, translated)


def set_block(src, marks, body):
    b, e = marks
    if b in src and e in src:
        return src[:src.index(b)] + b + "\n" + body + "\n" + src[src.index(e):]
    return src


INDEX_TITLE = "Lumi Trades: x402 seller trust you can verify"
INDEX_TAGLINE = "Bridging trust between agents"   # under the wordmark and in og/twitter descriptions; never in <title>
INDEX_DESC = ("Independent x402 seller trust list: Lumi test-buys sellers on Base, XRPL and Stellar with its own money and publishes signed evidence.")   # keep under ~155 characters (search snippets)
# x402scan and some unfurlers read <title>, og:title and the meta description without decoding HTML entities: keep "&", quotes
# and angle brackets out of these three (and the og/twitter description); use "and".
INDEX_OG_TITLE = INDEX_TITLE
INDEX_OG_DESC = INDEX_DESC   # og/twitter description = tagline + " · " + this (see og_desc)
INDEX_IMG_ALT = "Lumi wordmark under a Milky Way night sky"
SITE_AUTHOR = "Lumi"   # <meta name="author">
SITE_NAME = "Lumi"     # og:site_name on every page


# Cloudflare Web Analytics. lumitrades.io is DNS-only to GitHub Pages (not proxied), so Cloudflare's automatic setup cannot
# inject the beacon here (it only reaches proxied hosts such as api.lumitrades.io): every page carries the manual JS snippet.
# The site token is public by design (it is in the page source). Site: Cloudflare dash > Web Analytics > lumitrades.io.
CF_BEACON_TOKEN = "0212d2464cb04c11b35401da715265c6"
CF_BEACON = ("<!-- Cloudflare Web Analytics --><script defer src=\"https://static.cloudflareinsights.com/beacon.min.js\" "
             "data-cf-beacon='{\"token\": \"" + CF_BEACON_TOKEN + "\"}'></script><!-- End Cloudflare Web Analytics -->")
# hand-made pages the generators never write; build() keeps the beacon in them too
STATIC_PAGES = ("preview/index.html",)


_CF_BEACON_RE = re.compile(r"<!-- Cloudflare Web Analytics -->.*?<!-- End Cloudflare Web Analytics -->", re.S)


def with_beacon(html_src):
    """The page with the Cloudflare Web Analytics beacon just before </head> (idempotent; pages without a head are left alone).
    An existing beacon snippet is rewritten to the current CF_BEACON, so changing CF_BEACON_TOKEN updates every page."""
    if _CF_BEACON_RE.search(html_src):
        return _CF_BEACON_RE.sub(lambda m: CF_BEACON, html_src)
    if "static.cloudflareinsights.com/beacon.min.js" in html_src or "</head>" not in html_src:
        return html_src
    return html_src.replace("</head>", CF_BEACON + "\n</head>", 1)


def og_desc():
    return _(INDEX_TAGLINE) + " · " + _(INDEX_OG_DESC)


def lang_index(en_src, langs):
    """/<lang>/index.html from the English shell: translated text, head (lang, title, meta, canonical, hreflang, og:locale,
    JSON-LD), asset paths one level up. The generated blocks are refilled by the caller in this language."""
    url = f"{SITE}{L.prefix}"
    en_src = re.sub(r"<!--en-only-->.*?<!--/en-only-->", "", en_src, flags=re.S)  # English-only bits (e.g. the /trust-policy/ footer link)
    src = en_src.replace('<html lang="en" data-root="">', f'<html lang="{L.code}" data-root="../" data-home="">', 1)
    head, body = src.split("</head>", 1)

    def meta(h, attr, name, val):
        return re.sub(rf'(<meta {attr}="{re.escape(name)}" content=")[^"]*(">)', lambda m: m.group(1) + E(val) + m.group(2), h, count=1)
    head = re.sub(r"<title>[^<]*</title>", f"<title>{E(_(INDEX_TITLE))}</title>", head, count=1)
    head = meta(head, "name", "description", _(INDEX_DESC))
    head = meta(head, "name", "author", SITE_AUTHOR)
    for k in ("og:title", "twitter:title"):
        head = meta(head, "property" if k.startswith("og") else "name", k, _(INDEX_OG_TITLE))
    for k in ("og:description", "twitter:description"):
        head = meta(head, "property" if k.startswith("og") else "name", k, og_desc())
    for k in ("og:image:alt", "twitter:image:alt"):
        head = meta(head, "property" if k.startswith("og") else "name", k, _(INDEX_IMG_ALT))
    head = meta(head, "property", "og:url", url)
    head = head.replace('<link rel="canonical" href="https://lumitrades.io/">', f'<link rel="canonical" href="{url}">', 1)
    head = re.sub(r'<meta property="og:locale" content="[^"]*">\n?', "", head)
    head = re.sub(r'<meta property="og:locale:alternate" content="[^"]*">\n?', "", head)

    def ld(m):
        try:
            data = json.loads(m.group(1))
        except ValueError:
            return m.group(0)
        for x in data:
            if x.get("@type") == "WebSite":
                x.update({"url": url, "description": _(INDEX_DESC), "inLanguage": L.code})
        return '<script type="application/ld+json">' + json.dumps(data, ensure_ascii=False).replace("</", "<\\/") + "</script>"
    head = re.sub(r'<script type="application/ld\+json">(.*?)</script>', ld, head, count=1, flags=re.S)
    # generated blocks are refilled in this language by the caller: empty them so their English isn't translated
    for b0, b1 in [ISW, SWEEP, HSTATS]:
        if b0 in body and b1 in body:
            body = body[:body.index(b0) + len(b0)] + "\n" + body[body.index(b1):]
    body = i18n.translate_html(body, L)
    # asset / root paths: one level up (pages like trust/ and agents/ stay relative, i.e. inside this language)
    fix = lambda h: re.sub(r'((?:href|src)=")(?=(?:assets/|favicon\.ico|site\.webmanifest|feed\.xml|blog/|sellers/|data/|pricing/|about/|terms/))', r"\1../", h)
    head, body = fix(head), fix(body)
    head = head.replace('<script src="../assets/i18n.js', f'<script src="../assets/i18n/{L.code}.js?v={VERSION}" defer></script>\n<script src="../assets/i18n.js', 1)
    return head + "</head>" + body


def build(dry=False):
    """Render every page in every language. dry=True renders without writing (used by `i18n.py check`); returns the
    Lang objects (with their missing-key sets) in that case, else the list of changed paths."""
    global L, VERSION
    if not dry:
        import info_pages  # Legal placeholder guard: fails the build while /terms/ would carry [NOTICE ADDRESS: to supply]
        info_pages.check_placeholders()
    with open(os.path.join(ROOT, "index.html"), encoding="utf-8") as f:
        index = f.read()
    m = re.search(r"\?v=([0-9]{8}-[0-9]+)", index)
    V = VERSION = m.group(1) if m else "1"
    gen_date = dt.datetime.now(CT).date().isoformat()   # US Central, like every date the pages show
    nav_items = []  # no coin pages (retired Oct 25, 2026)
    changed = []
    langs = i18n.all_langs()

    def write(rel, content):
        if dry:
            return
        if rel.endswith(".html"):
            content = with_beacon(content)
        p = os.path.join(ROOT, rel)
        old = None
        if os.path.exists(p):
            with open(p, encoding="utf-8") as f:
                old = f.read()
        if old != content:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w", encoding="utf-8") as f:
                f.write(content)
            changed.append(rel)

    site_sm = []  # /agents/ + /trust/ + policy pages (scripts/site_pages.py)
    try:
        import site_pages
        vendors_doc = site_pages.fetch_vendors(dry)
        site_pages.fetch_badges((vendors_doc or {}).get("vendors") or [], dry)
        if not dry and os.environ.get("BUILD_REQUIRE_LIVE") == "1":
            import seller_pages as _sp_chk
            ids = [str(v["id"]) for v in (vendors_doc or {}).get("vendors") or [] if v.get("id")]
            _sp_chk.fetch_details(ids)  # warms the detail fetch so a partial one stops the build before any write
            if not all(site_pages.LIVE.values()):
                print(f"build_pages: live API data incomplete {site_pages.LIVE}; not writing pages (BUILD_REQUIRE_LIVE=1)", file=sys.stderr)
                sys.exit(5)
    except Exception as e:
        print(f"build_pages: WARNING site pages unavailable: {e!r}", file=sys.stderr)
        site_pages = vendors_doc = None
    seller_sm = []  # /sellers/<host-slug>/ (scripts/seller_pages.py, English only)
    info_sm = []  # /pricing/, /about/, /terms/ (scripts/info_pages.py, English only)
    try:
        import seller_pages
        if site_pages:
            site_pages.SELLER_SLUGS = seller_pages.slugs([v for v in (vendors_doc or {}).get("vendors") or [] if v.get("id")])
    except Exception as e:
        print(f"build_pages: WARNING seller pages unavailable: {e!r}", file=sys.stderr)
        seller_pages = None

    h = None
    for L in langs:
        h = types.SimpleNamespace(E=E, fp=fp, lvl=lvl, pc=pc, pct_txt=pct_txt, ctime=ctime, CT=CT, SITE=SITE,
                                  L=L, _=_, langs=langs, i18n=i18n, i18n_scripts=i18n_scripts, head_i18n=head_i18n)
        # ---- /agents/ + /trust/ + /how-it-works/ + policy pages ----
        if site_pages:
            try:
                sm_s = site_pages.build(h, site_chrome, nav_items, V, gen_date, write, vendors_doc)
                if L.en:
                    site_sm = sm_s
            except Exception as e:
                print(f"build_pages: WARNING agents/trust pages failed ({L.code}): {e!r}", file=sys.stderr)
        # ---- /sellers/<host-slug>/ (English only; one page per seller on the trust list, same data as /trust/) ----
        if L.en and site_pages and seller_pages:
            try:
                seller_sm = seller_pages.build(h, site_chrome, nav_items, V, gen_date, write, vendors_doc, dry)
            except Exception as e:
                print(f"build_pages: WARNING seller pages failed: {e!r}", file=sys.stderr)
        # ---- /pricing/, /about/, /terms/ (English only, scripts/info_pages.py; no try: a failure here fails the build) ----
        if L.en:
            import info_pages
            info_sm = info_pages.build(h, site_chrome, nav_items, V, gen_date, write)
        # ---- /blog/ index (English only; scripts/blog_index.py lists blog/<slug>/ posts) ----
        if L.en:
            try:
                import blog_index
                blog_index.build(h, site_chrome, V, gen_date, write)
            except Exception as e:
                print(f"build_pages: WARNING blog index failed: {e!r}", file=sys.stderr)

        # ---- the homepage in this language (/<lang>/index.html from the English shell) ----
        if not L.en:
            try:
                li = lang_index(index, langs)
                li = set_block(li, IHEAD, head_i18n("", langs))
                li = set_block(li, SEOHEAD, seo_head(f"{SITE}{L.prefix}", site_pages.PRICES if site_pages else []))
                li = set_block(li, ISW, i18n.switcher(L, "", langs))
                if site_pages:
                    li = set_block(li, TSTEPS, site_pages.steps_html(h) + "\n" + site_pages.chains_html(h))
                    li = set_block(li, SWEEP, site_pages.sweep_html(h, vendors_doc))
                    li = set_block(li, HSTATS, site_pages.stats_html(h, vendors_doc, home=True))
                write(f"{L.prefix}index.html", li)
            except Exception as e:
                print(f"build_pages: WARNING {L.code} homepage failed: {e!r}", file=sys.stderr)
    L = langs[0]
    if dry:
        return langs

    # ---- sitemap (every language, with xhtml:link hreflang alternates) ----
    def url_el(p, lm, fq, pr):
        out = []
        for x in langs:
            alts = "".join(f'<xhtml:link rel="alternate" hreflang="{y.code}" href="{SITE}{y.prefix}{p}"/>' for y in langs) + \
                (f'<xhtml:link rel="alternate" hreflang="x-default" href="{SITE}{p}"/>' if len(langs) > 1 else "")
            out.append(f'  <url><loc>{SITE}{x.prefix}{p}</loc><lastmod>{lm}</lastmod><changefreq>{fq}</changefreq><priority>{pr}</priority>'
                       + (alts if len(langs) > 1 else "") + '</url>')
        return out
    sm = ['<?xml version="1.0" encoding="UTF-8"?>',
          '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"' + (' xmlns:xhtml="http://www.w3.org/1999/xhtml"' if len(langs) > 1 else "") + '>']
    sm += url_el("", gen_date, "daily", "1.0")
    for p, lm, fq, pr in site_sm:
        sm += url_el(p, lm, fq, pr)
    # English-only /pricing/, /about/ and /terms/ (scripts/info_pages.py; no language versions yet)
    for p, lm, fq, pr in info_sm:
        sm.append(f'  <url><loc>{SITE}{p}</loc><lastmod>{lm}</lastmod><changefreq>{fq}</changefreq><priority>{pr}</priority></url>')
    # English-only static blog posts (blog/<slug>/index.html, hand-built; no language alternates)
    bdir = os.path.join(ROOT, "blog")
    if os.path.isfile(os.path.join(bdir, "index.html")):
        sm.append(f'  <url><loc>{SITE}blog/</loc><lastmod>{gen_date}</lastmod><changefreq>weekly</changefreq><priority>0.6</priority></url>')
    if os.path.isdir(bdir):
        for d in sorted(os.listdir(bdir)):
            if os.path.exists(os.path.join(bdir, d, "index.html")):
                sm.append(f'  <url><loc>{SITE}blog/{d}/</loc><lastmod>{gen_date}</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>')
    # English-only seller pages (scripts/seller_pages.py); noindex ones (no paid test-buy or attempt yet) stay out
    for p, lm, fq, pr in seller_sm:
        sm.append(f'  <url><loc>{SITE}{p}</loc><lastmod>{lm}</lastmod><changefreq>{fq}</changefreq><priority>{pr}</priority></url>')
    write("sitemap.xml", "\n".join(sm + ["</urlset>", ""]))

    # ---- Atom feed /feed.xml (scripts/feed.py): published blog posts only ----
    try:
        import feed
        write("feed.xml", feed.atom(ROOT))
    except Exception as e:
        print(f"build_pages: WARNING feed.xml failed: {e!r}", file=sys.stderr)

    # ---- generated blocks in the English homepage (index.html) ----
    fp_ = os.path.join(ROOT, "index.html")
    with open(fp_, encoding="utf-8") as f:
        cur = f.read()
    new = set_block(cur, IHEAD, head_i18n("", langs))
    new = set_block(new, SEOHEAD, seo_head(SITE, site_pages.PRICES if site_pages else []))
    new = set_block(new, ISW, i18n.switcher(L, "", langs))
    if site_pages:
        h.L, h._ = L, _
        new = set_block(new, TSTEPS, site_pages.steps_html(h) + "\n" + site_pages.chains_html(h))
    if site_pages and site_pages.sweep(vendors_doc):
        h.L, h._ = L, _
        new = set_block(new, SWEEP, site_pages.sweep_html(h, vendors_doc))
        new = set_block(new, HSTATS, site_pages.stats_html(h, vendors_doc, home=True))
    new = with_beacon(new)
    if new != cur:
        write("index.html", new)
    for path in STATIC_PAGES:
        fp_ = os.path.join(ROOT, path)
        if os.path.exists(fp_):
            with open(fp_, encoding="utf-8") as f:
                cur = f.read()
            if with_beacon(cur) != cur:
                write(path, cur)
    changed += i18n.bundle(langs)
    return changed


def lang_dirs():
    return [c for c in i18n.codes() if c != "en"]


if __name__ == "__main__":
    ch = build()
    if "--paths" in sys.argv:
        # for publish.sh: every generated page + sitemap (unchanged ones are no-ops for git add), index.html only if changed
        outs = []
        for pre in [""] + [c + "/" for c in lang_dirs()]:
            if pre and os.path.exists(os.path.join(ROOT, pre, "index.html")):
                outs.append(f"{pre}index.html")
            outs += [f"{pre}{d}/index.html" for d in ("agents", "trust", "how-it-works", "privacy", "contact", "trust-policy", "top-sellers") if os.path.exists(os.path.join(ROOT, pre, d, "index.html"))]
        sdir = os.path.join(ROOT, "sellers")  # English-only seller pages (scripts/seller_pages.py)
        if os.path.isdir(sdir):
            outs += sorted(f"sellers/{d}/index.html" for d in os.listdir(sdir) if os.path.exists(os.path.join(sdir, d, "index.html")))
        outs += [f"{d}/index.html" for d in ("pricing", "prices", "about", "terms") if os.path.exists(os.path.join(ROOT, d, "index.html"))]
        outs += ["prices/index.json", "blog/index.html", "sitemap.xml", "feed.xml"]
        outs = [o for o in outs if os.path.exists(os.path.join(ROOT, o))]
        print("\n".join(outs + [x for x in ch if x not in outs]))
    elif "--quiet" in sys.argv:
        print("\n".join(ch))
    else:
        print(f"build_pages: {len(ch)} changed: " + (", ".join(ch) or "nothing"))
